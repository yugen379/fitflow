// Sanity: reject anything whose macros cannot produce its calorie figure.
// Same gate as batch 1, plus the Firestore rule's bound (macros may not imply
// more than 1.5x the calories + 50), so nothing here would be refused there.
const implied = (f) => f.protein * 4 + f.carbs * 4 + f.fats * 9;
const suspect = added.filter((f) => {
  if (f.alcohol) return implied(f) > f.calories;
  return Math.abs(implied(f) - f.calories) > Math.max(120, f.calories * 0.30) || implied(f) > f.calories * 1.5 + 50;
});

